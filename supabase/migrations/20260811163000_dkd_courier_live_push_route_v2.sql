create or replace function public.dkd_courier_order_alert_webhook()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare dkd_config_value public.dkd_internal_webhook_config%rowtype; dkd_event_value text:=''; dkd_old_status_value text:=''; dkd_new_status_value text:=lower(coalesce(new.status,'')); dkd_old_pickup_value text:=''; dkd_new_pickup_value text:=lower(coalesce(new.pickup_status,''));
begin
  select * into dkd_config_value from public.dkd_internal_webhook_config where dkd_key='courier_order_alert';
  if not found or coalesce(dkd_config_value.dkd_url,'')='' or coalesce(dkd_config_value.dkd_secret,'')='' then return new; end if;
  if tg_op='INSERT' then
    if coalesce(new.is_active,true)=true and dkd_new_status_value in('open','ready','published','pending','courier_pool','new','waiting') and new.assigned_user_id is null then dkd_event_value:='new_order'; else return new; end if;
  elsif tg_op='UPDATE' then
    dkd_old_status_value:=lower(coalesce(old.status,'')); dkd_old_pickup_value:=lower(coalesce(old.pickup_status,''));
    if (dkd_new_status_value in('completed','delivered','done','finished') or dkd_new_pickup_value in('delivered','completed')) and not(dkd_old_status_value in('completed','delivered','done','finished') or dkd_old_pickup_value in('delivered','completed')) then dkd_event_value:='delivered';
    elsif (dkd_new_status_value in('picked_up','to_customer','delivering') or dkd_new_pickup_value='picked_up') and not(dkd_old_status_value in('picked_up','to_customer','delivering') or dkd_old_pickup_value='picked_up') then dkd_event_value:='picked_up';
    elsif dkd_new_status_value in('accepted','assigned','to_pickup') and dkd_old_status_value not in('accepted','assigned','to_pickup') then dkd_event_value:='accepted'; else return new; end if;
  else return new; end if;
  perform net.http_post(url:=dkd_config_value.dkd_url,headers:=jsonb_build_object('Content-Type','application/json','x-dkd-webhook-secret',dkd_config_value.dkd_secret),body:=jsonb_build_object('type',tg_op,'table',tg_table_name,'schema',tg_table_schema,'event',dkd_event_value,'record',to_jsonb(new),'old_record',case when tg_op='UPDATE' then to_jsonb(old) else null end),timeout_milliseconds:=8000);
  return new;
exception when others then return new;
end;$function$;
