create or replace function public.dkd_delivery_place_resolve_dkd(dkd_param_query text,dkd_param_city text default null)
returns jsonb language plpgsql stable security definer set search_path to 'public' as $function$
declare dkd_query_value text:=lower(trim(coalesce(dkd_param_query,''))); dkd_city_value text:=lower(trim(coalesce(dkd_param_city,''))); dkd_row_value public.dkd_verified_delivery_places%rowtype;
begin
  if dkd_query_value='' then return jsonb_build_object('dkd_ok_value',false,'dkd_reason_value','query_required'); end if;
  select p.* into dkd_row_value from public.dkd_verified_delivery_places p where p.dkd_is_active is true and (dkd_city_value='' or lower(coalesce(p.dkd_city,''))=dkd_city_value) and (dkd_query_value like '%'||lower(p.dkd_name)||'%' or exists(select 1 from unnest(p.dkd_aliases) dkd_alias_value where dkd_query_value like '%'||lower(dkd_alias_value)||'%' or lower(dkd_alias_value) like '%'||dkd_query_value||'%')) order by length(p.dkd_name) desc,p.dkd_id asc limit 1;
  if not found then return jsonb_build_object('dkd_ok_value',false,'dkd_reason_value','not_found'); end if;
  return jsonb_build_object('dkd_ok_value',true,'dkd_name',dkd_row_value.dkd_name,'dkd_address_text',dkd_row_value.dkd_address_text,'dkd_lat',dkd_row_value.dkd_lat,'dkd_lng',dkd_row_value.dkd_lng,'dkd_city',dkd_row_value.dkd_city,'dkd_district',dkd_row_value.dkd_district);
end;$function$;
grant execute on function public.dkd_delivery_place_resolve_dkd(text,text) to authenticated;

create or replace function public.dkd_courier_job_live_metrics_set_dkd(dkd_param_job_id bigint,dkd_param_distance_km numeric,dkd_param_eta_min integer)
returns jsonb language plpgsql security definer set search_path to 'public','auth' as $function$
declare dkd_user_id_value uuid:=auth.uid(); dkd_distance_value numeric:=greatest(0,coalesce(dkd_param_distance_km,0)); dkd_eta_value integer:=greatest(0,coalesce(dkd_param_eta_min,0));
begin
  if dkd_user_id_value is null then return jsonb_build_object('dkd_ok_value',false,'dkd_reason_value','auth_required'); end if;
  update public.dkd_courier_jobs set distance_km=round(dkd_distance_value,2),eta_min=dkd_eta_value,updated_at=now() where id=dkd_param_job_id and assigned_user_id=dkd_user_id_value and coalesce(is_active,true)=true;
  if not found then return jsonb_build_object('dkd_ok_value',false,'dkd_reason_value','job_not_assigned_or_inactive'); end if;
  return jsonb_build_object('dkd_ok_value',true,'dkd_distance_km',round(dkd_distance_value,2),'dkd_eta_min',dkd_eta_value);
end;$function$;
grant execute on function public.dkd_courier_job_live_metrics_set_dkd(bigint,numeric,integer) to authenticated;

