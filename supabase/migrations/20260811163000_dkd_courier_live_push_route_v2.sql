create table if not exists public.dkd_native_push_tokens (
  dkd_id bigint generated by default as identity primary key,
  dkd_user_id uuid not null references auth.users(id) on delete cascade,
  dkd_token text not null unique,
  dkd_platform text,
  dkd_app_mode text,
  dkd_device_name text,
  dkd_is_active boolean not null default true,
  dkd_last_seen_at timestamptz not null default now(),
  dkd_created_at timestamptz not null default now(),
  dkd_updated_at timestamptz not null default now()
);
alter table public.dkd_native_push_tokens enable row level security;
revoke all on table public.dkd_native_push_tokens from anon, authenticated;
grant select, insert, update, delete on table public.dkd_native_push_tokens to service_role;
create index if not exists dkd_native_push_tokens_user_active_idx on public.dkd_native_push_tokens(dkd_user_id, dkd_is_active, dkd_last_seen_at desc);

create or replace function public.dkd_upsert_native_push_token(
  dkd_param_token text,
  dkd_param_platform text default null,
  dkd_param_app_mode text default null,
  dkd_param_device_name text default null
) returns jsonb language plpgsql security definer set search_path to 'public','auth' as $function$
declare dkd_user_id_value uuid:=auth.uid(); dkd_token_value text:=nullif(trim(coalesce(dkd_param_token,'')),'');
begin
  if dkd_user_id_value is null then return jsonb_build_object('dkd_ok_value',false,'dkd_reason_value','auth_required'); end if;
  if dkd_token_value is null then return jsonb_build_object('dkd_ok_value',false,'dkd_reason_value','token_required'); end if;
  insert into public.dkd_native_push_tokens(dkd_user_id,dkd_token,dkd_platform,dkd_app_mode,dkd_device_name,dkd_is_active,dkd_last_seen_at,dkd_created_at,dkd_updated_at)
  values(dkd_user_id_value,dkd_token_value,nullif(trim(coalesce(dkd_param_platform,'')),''),nullif(trim(coalesce(dkd_param_app_mode,'')),''),nullif(trim(coalesce(dkd_param_device_name,'')),''),true,now(),now(),now())
  on conflict(dkd_token) do update set dkd_user_id=excluded.dkd_user_id,dkd_platform=excluded.dkd_platform,dkd_app_mode=excluded.dkd_app_mode,dkd_device_name=excluded.dkd_device_name,dkd_is_active=true,dkd_last_seen_at=now(),dkd_updated_at=now();
  return jsonb_build_object('dkd_ok_value',true,'dkd_reason_value','native_push_token_upserted');
end;$function$;
grant execute on function public.dkd_upsert_native_push_token(text,text,text,text) to authenticated;

